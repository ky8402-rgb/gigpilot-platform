/**
 * Autonomous Software Work Order Queue Solver
 * Automatically picks pending software-related jobs from the web app,
 * executes them, marks them completed, updates records, and delivers automatically if enabled.
 * Also automatically invokes Tool 2 to close the work order and release escrow payout if enabled.
 */
export async function autoSolvePendingSoftwareQueue(params: {
  orders?: any[];
  autoDeliver?: boolean;
  autoReleaseEscrow?: boolean;
  payoutMethod?: 'paypal' | 'upi' | 'bank_wire';
  maxJobs?: number;
  categoryFilter?: string;
}): Promise<{
  success: boolean;
  processedCount: number;
  deliveredCount: number;
  escrowReleasedCount: number;
  results: Array<{
    orderId: string | number;
    title: string;
    filesCount: number;
    delivered: boolean;
    escrowReleased: boolean;
    releaseId?: string;
    payoutDestination?: string;
    amountUsd?: number;
    amountInr?: number;
  }>;
}> {
  const maxJobs = params.maxJobs || 5;
  const live = getAllLiveOrders();
  const candidatePool = (params.orders && Array.isArray(params.orders) && params.orders.length > 0)
    ? params.orders
    : (live.length > 0 ? live : [
        {
          id: 'job_soft_101',
          title: 'Full Stack React & Node.js Payment Integration',
          description: 'Integrate Stripe and PayPal checkout flows with HMAC webhook validation and automated escrow reconciliation.',
          amount: 450,
          category: 'Software Engineering',
          status: 'pending',
          tags: ['React', 'TypeScript', 'Node.js', 'Express', 'Stripe', 'PayPal']
        },
        {
          id: 'job_soft_102',
          title: 'Python FastAPI Microservice with Redis Rate Limiting',
          description: 'High-throughput async REST API with token bucket rate limiting and Docker containerization.',
          amount: 380,
          category: 'Backend Development',
          status: 'pending',
          tags: ['Python', 'FastAPI', 'Redis', 'Docker']
        }
      ]);

  const shouldAutoRelease = params.autoReleaseEscrow !== false;

  // Filter for software-related orders that are pending / active and not yet completed
  const softwareKeywords = /software|developer|engineer|api|backend|frontend|react|python|fullstack|node|app|database|script|automation|web/i;
  
  const candidateOrders = candidatePool.filter(o => {
    const status = String(o.status || '').toLowerCase();
    if (status === 'completed' || status === 'closed_settled') return false;
    const catMatch = o.category ? softwareKeywords.test(o.category) : false;
    const titleMatch = softwareKeywords.test(o.title || '');
    return catMatch || titleMatch;
  }).slice(0, maxJobs);

  const results: Array<{
    orderId: string | number;
    title: string;
    filesCount: number;
    delivered: boolean;
    escrowReleased: boolean;
    releaseId?: string;
    payoutDestination?: string;
    amountUsd?: number;
    amountInr?: number;
  }> = [];
  let deliveredCount = 0;
  let escrowReleasedCount = 0;

  for (const order of candidateOrders) {
    try {
      // 1. Tool 1: Autonomous Software Execution
      const deliverable = await executeWorkOrderDeliverable({
        orderId: order.id,
        title: order.title,
        description: order.description,
        category: order.category,
        tags: (order as any).tags,
        budget: order.amount,
      });

      // 2. Client Delivery
      let delivered = false;
      if (params.autoDeliver) {
        await deliverWorkOrderToClient({
          orderId: order.id,
          clientName: (order as any).client || (order as any).employer || 'Client',
          customNote: deliverable.clientHandoverNote,
          requestPayment: true,
        });
        delivered = true;
        deliveredCount++;
      }

      // 3. Tool 2: Automatic Escrow Closer & Payment Disbursement
      let escrowReleased = false;
      let releaseId: string | undefined;
      let payoutDestination: string | undefined;
      let amountUsd = Number(order.amount || 250);
      let amountInr = Math.round(amountUsd * 86.85);

      if (shouldAutoRelease) {
        try {
          const { closeWorkOrderAndReleaseEscrow } = await import('./workOrderCloserService.js');
          const release = await closeWorkOrderAndReleaseEscrow({
            orderId: order.id,
            payoutMethod: params.payoutMethod || 'paypal',
            clientNotes: `Automatic pipeline: Tool 1 completed software job, and Tool 2 verified checksum & released escrow.`,
            verifiedChecksum: deliverable.checksum,
          });

          escrowReleased = true;
          escrowReleasedCount++;
          releaseId = release.releaseId;
          payoutDestination = release.payoutDestination;
          amountUsd = release.escrowAmountUsd;
          amountInr = release.escrowAmountInr;
        } catch (escrowErr) {
          console.warn(`[WorkExecutionEngine] Auto-escrow release note for #${order.id}:`, escrowErr);
        }
      }

      results.push({
        orderId: order.id,
        title: order.title,
        filesCount: deliverable.files.length,
        delivered,
        escrowReleased,
        releaseId,
        payoutDestination,
        amountUsd,
        amountInr,
      });
    } catch (orderErr: any) {
      console.error(`[WorkExecutionEngine] Failed to auto-solve order #${order.id}:`, orderErr);
    }
  }

  logActivityEvent({
    source: 'WorkExecutionEngine',
    type: 'QUEUE_AUTO_SOLVED',
    status: 'success',
    summary: `Autonomous Software Queue Solver completed ${results.length} work orders (${deliveredCount} delivered, ${escrowReleasedCount} escrow settled via Tool 2)`,
    tags: ['auto_solver', 'software_jobs', 'queue_pilot', 'escrow_closer']
  });

  return {
    success: true,
    processedCount: results.length,
    deliveredCount,
    escrowReleasedCount,
    results,
  };
}

/**
 * Deliver completed work order to client (dispatches into client chat and links payment)
 */
export async function deliverWorkOrderToClient(params: {
  orderId: string | number;
  clientName?: string;
  customNote?: string;
  requestPayment?: boolean;
}): Promise<{
  success: boolean;
  message: string;
  conversationId?: string;
  deliverable: WorkExecutionDeliverable;
}> {
  const deliverable = getOrderDeliverable(params.orderId);
  if (!deliverable) {
    throw new Error('No deliverable found for order #' + params.orderId);
  }

  // Find or create conversation for this client
  const clientName = params.clientName || 'Client';
  const allConvs = getAllConversations();
  let targetConv = allConvs.find(c => 
    c.clientName.toLowerCase() === clientName.toLowerCase() ||
    c.projectTitle.toLowerCase() === deliverable.jobTitle.toLowerCase()
  );

  if (!targetConv) {
    targetConv = createConversation({
      clientName,
      projectTitle: deliverable.jobTitle,
      projectBudget: 350,
      platform: 'Freelancer',
      initialMessage: `Hello ${clientName}! Deliverables for "${deliverable.jobTitle}" have been engineered and verified.`
    });
  }

  // Construct deliverable files list
  const fileListText = deliverable.files.map(f => `📁 \`${f.filename}\` (${f.description})`).join('\n');
  const handoverText = params.customNote || deliverable.clientHandoverNote;

  const fullMessage = `${handoverText}\n\n**Deliverable Package Summary:**\n${deliverable.summary}\n\n**Included Production Files (${deliverable.files.length} files, ${deliverable.linesOfCode} LOC):**\n${fileListText}\n\n**Security Verification:**\n- SHA-256 Checksum: \`${deliverable.checksum}\`\n- Architecture: ${deliverable.architectureNotes}`;

  // Generate payment link if requested
  const paymentLinks = getPaymentCollectionLinks({
    amountUsd: 350,
    clientName,
    invoiceRef: `INV-${params.orderId}`,
    memo: `Deliverables: ${deliverable.jobTitle}`
  });

  addMessageToConversation(targetConv.id, {
    sender: 'freelancer',
    senderName: 'Kundan (Freelancer)',
    text: fullMessage,
    actionPayload: params.requestPayment !== false ? {
      type: 'payment_request',
      amount: 350,
      link: paymentLinks.paypalUrl,
      label: `Release Milestone Payment ($350 USD)`
    } : {
      type: 'deliverable_link',
      label: `Verified SHA-256: ${deliverable.checksum}`
    }
  });

  // Mark in-memory order status
  const allOrders = getAllLiveOrders();
  const orderMatch = allOrders.find(o => String(o.id) === String(params.orderId));
  if (orderMatch) {
    orderMatch.status = 'completed';
    (orderMatch as any).delivered_at = new Date().toISOString();
  }

  logActivityEvent({
    source: 'WorkExecutionEngine',
    type: 'WORK_DELIVERED_TO_CLIENT',
    status: 'success',
    summary: `Deliverables for "${deliverable.jobTitle}" delivered to client ${clientName} in Conversation #${targetConv.id}`,
    tags: ['work_delivered', 'client_messaging', 'payment_requested']
  });

  return {
    success: true,
    message: `Deliverable package dispatched to ${clientName} with verified SHA-256 checksum and payment invoice.`,
    conversationId: targetConv.id,
    deliverable
  };
}

