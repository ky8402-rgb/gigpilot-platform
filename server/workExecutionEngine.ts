/**
 * Execute work autonomously using Gemini AI with resilient fallbacks
 */
export async function executeWorkOrderDeliverable(params: {
  orderId: string | number;
  title: string;
  description?: string;
  category?: string;
  tags?: string[];
  budget?: number;
  requirements?: string;
}): Promise<WorkExecutionDeliverable> {
  const startTime = Date.now();
  const title = params.title || 'Freelance Project Task';
  const description = params.description || '';
  const category = params.category || 'Software Development';
  const tags = params.tags || [];

  let files: DeliverableFile[] = [];
  let summary = '';
  let architectureNotes = '';
  let verificationChecklist: string[] = [];
  let clientHandoverNote = '';
  let modelUsed = 'gemini-3.8-flash';

  const ai = getGeminiAI();

  if (ai) {
    try {
      const learnedContext = buildLearnedContextPrompt(category, tags, title);
      const prompt = `You are a Senior Full-Stack Principal Engineer and Freelance Contractor.
A client hired you for the following freelance project:
Title: "${title}"
Category: ${category}
Tags: ${tags.join(', ')}
Client Requirements & Details:
${description}
${params.requirements ? `Additional Notes: ${params.requirements}` : ''}
${learnedContext}

YOUR TASK:
ACTUALLY DO THE WORK. Do NOT output marketing text or generic explanations.
Generate the REAL, production-grade source code, configuration files, test suites, and documentation that solves the client's request completely.

OUTPUT FORMAT: Return a valid JSON object strictly matching this schema:
{
  "summary": "Short 2-3 sentence overview of what was built and delivered",
  "architectureNotes": "Key architecture choices, frameworks, and patterns used and why they were chosen",
  "verificationChecklist": ["Checked item 1", "Checked item 2", "Checked item 3", "Checked item 4"],
  "clientHandoverNote": "Professional, courteous message to client summarizing delivery and how to run it",
  "files": [
    {
      "filename": "path/filename.ext",
      "language": "typescript|python|json|markdown|sql|html|css",
      "description": "What this file does",
      "content": "Complete, working source code for this file without placeholders"
    }
  ]
}

Provide at least 3 essential files (main source file, automated test file, and README.md).`;

      const result = await generateContentResilient({
        model: 'gemini-3.8-flash',
        fallbackModels: ['gemini-3.1-flash-lite', 'gemini-3.1-pro-preview'],
        contents: prompt,
        config: {
          responseMimeType: 'application/json',
          temperature: 0.2,
        },
        maxRetries: 2,
      });

      modelUsed = result.modelUsed;
      const parsed = JSON.parse(result.text);

      if (parsed.files && Array.isArray(parsed.files) && parsed.files.length > 0) {
        files = parsed.files;
        summary = parsed.summary || `Deliverables generated for ${title}`;
        architectureNotes = parsed.architectureNotes || 'Standard modular architecture';
        verificationChecklist = parsed.verificationChecklist || ['Verified requirements', 'Passed tests'];
        clientHandoverNote = parsed.clientHandoverNote || `Project "${title}" has been completed.`;
      }
    } catch (err: any) {
      console.warn('[WorkExecutionEngine] Gemini generation fallback triggered:', err?.message || err);
    }
  }

  // If Gemini was unavailable or JSON parse failed, use the rich fallback generator
  if (files.length === 0) {
    const fallback = generateFallbackDeliverables(title, description, category, tags);
    files = fallback.files;
    summary = fallback.summary;
    architectureNotes = fallback.architectureNotes;
    verificationChecklist = fallback.verificationChecklist;
    clientHandoverNote = fallback.clientHandoverNote;
    modelUsed = 'rule-based-autonomous-generator';
  }

  const executionTimeMs = Date.now() - startTime;
  const totalLoc = files.reduce((acc, f) => acc + (f.content.split('\n').length || 0), 0);
  const checksum = crypto.createHash('sha256').update(files.map(f => f.content).join('')).digest('hex').slice(0, 16);

  const deliverable: WorkExecutionDeliverable = {
    orderId: params.orderId,
    jobTitle: title,
    status: 'completed',
    executedAt: new Date().toISOString(),
    executionTimeMs,
    files,
    summary,
    architectureNotes,
    verificationChecklist,
    clientHandoverNote,
    linesOfCode: totalLoc,
    modelUsed,
    checksum,
  };

  // Cache in deliverableStore
  deliverableStore.set(String(params.orderId), deliverable);

  // Record into persistent self-learning memory & heuristics
  try {
    recordLearningFromCompletedJob({
      orderTitle: title,
      category,
      tags,
      linesOfCode: totalLoc,
      executionTimeMs,
      architectureNotes,
    });
  } catch (learnErr: any) {
    console.warn('[WorkExecutionEngine] Learning recording notice:', learnErr?.message || learnErr);
  }

  // Update in-memory order if it exists
  const allOrders = getAllLiveOrders();
  const targetOrder = allOrders.find(o => String(o.id) === String(params.orderId));
  if (targetOrder) {
    targetOrder.status = 'completed';
    (targetOrder as any).completed_at = deliverable.executedAt;
    (targetOrder as any).deliverables = deliverable.summary;
    (targetOrder as any).deliverablePackage = deliverable;
  }

  logActivityEvent({
    source: 'WorkExecutionEngine',
    type: 'WORK_DELIVERABLE_COMPLETED',
    status: 'success',
    summary: `Autonomous Work Executed for "${title}": ${files.length} files (${totalLoc} LOC) delivered via ${modelUsed}`,
    tags: ['work_execution', 'ai_delivery', 'proof_of_work'],
  });

  return deliverable;
}

/**
 * Retrieve cached deliverable for an order
 */
export function getOrderDeliverable(orderId: string | number): WorkExecutionDeliverable | null {
  return deliverableStore.get(String(orderId)) || null;
}

/**
 * Retrieve all delivered work
 */
export function getAllDeliverables(): WorkExecutionDeliverable[] {
  return Array.from(deliverableStore.values());
}

